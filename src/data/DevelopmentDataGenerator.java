    private static String nullable(Integer value) {
        return value == null ? "NULL" : Integer.toString(value);
    }

    private static String quote(String value) {
        return "'" + value.replace("'", "''") + "'";
    }

    private static String money(int cents) {
        return String.format(Locale.ROOT, "%d.%02d", cents / 100, Math.abs(cents % 100));
    }

    private static String decimalFromHundredths(int hundredths) {
        return String.format(Locale.ROOT, "%d.%02d", hundredths / 100,
                Math.abs(hundredths % 100));
    }

    private static String tuple(Object... values) {
        StringBuilder tuple = new StringBuilder("(");
        for (int index = 0; index < values.length; index++) {
            if (index > 0) {
                tuple.append(", ");
            }
            tuple.append(values[index]);
        }
        return tuple.append(')').toString();
    }

    private static void appendValues(StringBuilder sql, String header, List<String> rows) {
        require(!rows.isEmpty(), "Generated INSERT statements may not be empty.");
        line(sql, header);
        for (int index = 0; index < rows.size(); index++) {
            line(sql, "    " + rows.get(index) + (index + 1 == rows.size() ? ";" : ","));
        }
    }

    private static void line(StringBuilder sql, String text) {
        sql.append(text).append(System.lineSeparator());
    }

    private static void require(boolean condition, String message) {
        if (!condition) {
            throw new IllegalStateException(message);
        }
    }

