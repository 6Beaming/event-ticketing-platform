    public static String generateSql() {
        Dataset dataset = buildDataset();
        validateDataset(dataset);

        StringBuilder sql = new StringBuilder();
        line(sql, "-- Generated by data.DevelopmentDataGenerator. Do not edit by hand.");
        line(sql, "-- Complete PDF-compliant sample data with stable IDs and relative UTC dates.");
        line(sql, "SET NAMES utf8mb4;");
        line(sql, "START TRANSACTION;");
        line(sql, "");
        appendProfiles(sql);
        appendTaxonomy(sql);
        appendVenues(sql, dataset);
        appendEvents(sql, dataset);
        appendPerformancesAndInventory(sql, dataset);
        appendPurchasesAndTickets(sql, dataset);
        appendCancellations(sql, dataset);
        appendResaleMarket(sql, dataset);
        appendCustomerRestrictions(sql);
        appendReviews(sql, dataset);
        line(sql, "COMMIT;");
        line(sql, "");
        appendCountChecks(sql);
        return sql.toString();
    }

