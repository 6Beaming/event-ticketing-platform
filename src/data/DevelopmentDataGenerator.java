    private static String purchaseDateExpression(PerformanceSpec performance, int purchaseId) {
        int sequence = purchaseId - 7001;
        int daysAgo;
        if ("cancelled".equals(performance.status)) {
            daysAgo = performance.cancellationDaysAgo + 25 + (sequence % 25);
        } else if (performance.offsetDays < 0) {
            daysAgo = Math.min(360, (-performance.offsetDays) + 20 + (sequence % 25));
        } else {
            daysAgo = 1 + ((sequence * 11) % 350);
        }
        return daysAgoExpression(daysAgo);
    }

    private static String daysAgoExpression(int daysAgo) {
        return "DATE_SUB(UTC_TIMESTAMP(), INTERVAL " + daysAgo + " DAY)";
    }

