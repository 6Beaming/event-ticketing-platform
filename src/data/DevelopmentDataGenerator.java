    private static void initializePricingAndInventory(Dataset dataset) {
        int nextSeatId = 610001;
        int nextGaId = 620001;

        for (PerformanceSpec performance : dataset.performances) {
            VenueSpec venue = venueById(dataset, performance.venueId);
            int eventOffset = performance.eventId - FIRST_EVENT_ID;
            int basePrice = 6500 + ((eventOffset % 5) * 900) + ((performance.id % 4) * 250);
            performance.tierPrices.put("P1", basePrice + 3500);
            performance.tierPrices.put("P2", basePrice + 1200);
            performance.tierPrices.put("P3", basePrice - 800);

            if (performance.id == 6001) {
                performance.tierPrices.put("P1", 12000);
                performance.tierPrices.put("P2", 8000);
                performance.tierPrices.put("P3", 5000);
            } else if (performance.id == 6002) {
                performance.tierPrices.put("P1", 13500);
                performance.tierPrices.put("P2", 9000);
                performance.tierPrices.put("P3", 5500);
            }

            for (int sectionIndex = 0; sectionIndex < venue.sections.size(); sectionIndex++) {
                SectionSpec section = venue.sections.get(sectionIndex);
                String tierCode = "P" + (sectionIndex + 1);
                if (performance.id == 6002 && sectionIndex < 2) {
                    tierCode = sectionIndex == 0 ? "P2" : "P1";
                }
                performance.sectionTiers.put(section.name, tierCode);

                if (section.generalAdmission) {
                    GaInventory ga = new GaInventory(nextGaId++, performance.id, venue.id,
                            section.name, section.capacity);
                    dataset.gaInventory.add(ga);
                    dataset.gaByPerformance.computeIfAbsent(performance.id, ignored -> new ArrayList<>()).add(ga);
                } else {
                    for (String rowName : section.rowNames) {
                        for (int seatNumber = 1; seatNumber <= section.seatsPerRow; seatNumber++) {
                            boolean blocked = shouldBlockSeat(performance.id, section, rowName, seatNumber);
                            SeatInventory seat = new SeatInventory(nextSeatId++, performance.id, venue.id,
                                    section.name, rowName, seatNumber, blocked);
                            dataset.seatInventory.add(seat);
                            dataset.seatsByPerformance.computeIfAbsent(performance.id,
                                    ignored -> new ArrayList<>()).add(seat);
                        }
                    }
                }
            }
        }
    }

    private static boolean shouldBlockSeat(int performanceId, SectionSpec section,
            String rowName, int seatNumber) {
        if (SOLD_OUT_PERFORMANCES.contains(performanceId)) {
            return false;
        }
        if (performanceId == SPECIAL_AVAILABLE_PERFORMANCE
                && "Orchestra".equals(section.name)) {
            return ("A".equals(rowName) && seatNumber == 12)
                    || ("B".equals(rowName) && seatNumber % 2 == 0);
        }
        return performanceId % 9 == 0
                && seatNumber == section.seatsPerRow
                && rowName.equals(section.rowNames[0]);
    }

    private static void createPurchases(Dataset dataset) {
        Map<Integer, Integer> orderCounts = buildOrderCounts(dataset);
        Map<Integer, Integer> createdByPerformance = new HashMap<>();

        dataset.nextTicketId = 8003;
        createPurchase(dataset, 7001, 2001, 6001, 0, new int[] {8001, 8003, 8004});
        createdByPerformance.put(6001, 1);
        dataset.nextTicketId = 8005;
        createPurchase(dataset, 7002, 2002, 6002, 0, new int[] {8002, 8005, 8006});
        createdByPerformance.put(6002, 1);
        dataset.nextTicketId = 8007;

        int nextPurchaseId = 7003;
        int regularCustomerOffset = 0;
        for (PerformanceSpec performance : dataset.performances) {
            int target = orderCounts.get(performance.id);
            int alreadyCreated = createdByPerformance.getOrDefault(performance.id, 0);
            for (int performanceOrderIndex = alreadyCreated;
                    performanceOrderIndex < target; performanceOrderIndex++) {
                int customerId;
                if (performance.id == 6003 && performanceOrderIndex < 3) {
                    customerId = 2001;
                } else if (performance.id == 6003 && performanceOrderIndex < 6) {
                    customerId = 2002;
                } else {
                    customerId = 2003 + (regularCustomerOffset % 98);
                    regularCustomerOffset++;
                }
                int[] ticketIds = {
                    dataset.nextTicketId++, dataset.nextTicketId++, dataset.nextTicketId++
                };
                createPurchase(dataset, nextPurchaseId++, customerId, performance.id,
                        performanceOrderIndex, ticketIds);
            }
        }
    }

    private static Map<Integer, Integer> buildOrderCounts(Dataset dataset) {
        Map<Integer, Integer> orderCounts = new LinkedHashMap<>();
        orderCounts.put(6001, 4);
        orderCounts.put(6002, 5);
        orderCounts.put(6003, venueCapacity(venueById(dataset, performanceById(dataset, 6003).venueId)) / 3);
        orderCounts.put(6007, venueCapacity(venueById(dataset, performanceById(dataset, 6007).venueId)) / 3);
        orderCounts.put(6019, venueCapacity(venueById(dataset, performanceById(dataset, 6019).venueId)) / 3);
        orderCounts.put(6004, 2);
        orderCounts.put(6022, 2);
        orderCounts.put(6025, 3);
        orderCounts.put(6058, 5);
        orderCounts.put(6060, 5);
        for (int performanceId : CONFIGURABLE_PERFORMANCES) {
            orderCounts.put(performanceId, 0);
        }

        int assigned = orderCounts.values().stream().mapToInt(Integer::intValue).sum();
        int remainingWithFive = PURCHASE_COUNT - assigned - ((PERFORMANCE_COUNT - orderCounts.size()) * 4);
        for (PerformanceSpec performance : dataset.performances) {
            if (!orderCounts.containsKey(performance.id)) {
                orderCounts.put(performance.id, remainingWithFive > 0 ? 5 : 4);
                if (remainingWithFive > 0) {
                    remainingWithFive--;
                }
            }
        }
        require(orderCounts.values().stream().mapToInt(Integer::intValue).sum() == PURCHASE_COUNT,
                "Purchase allocation must total exactly " + PURCHASE_COUNT + ".");
        return orderCounts;
    }

    private static void createPurchase(Dataset dataset, int purchaseId, int customerId,
            int performanceId, int performanceOrderIndex, int[] ticketIds) {
        PerformanceSpec performance = performanceById(dataset, performanceId);
        String transactionDate = purchaseDateExpression(performance, purchaseId);
        TransactionSpec transaction = TransactionSpec.purchase(purchaseId, customerId,
                paymentId(customerId), performanceId, transactionDate);
        dataset.purchases.add(transaction);

        for (int ticketIndex = 0; ticketIndex < ticketIds.length; ticketIndex++) {
            TicketSpec ticket = allocateTicket(dataset, performance, purchaseId, customerId,
                    ticketIds[ticketIndex], performanceOrderIndex, ticketIndex);
            dataset.tickets.add(ticket);
        }
    }

    private static TicketSpec allocateTicket(Dataset dataset, PerformanceSpec performance,
            int purchaseId, int customerId, int ticketId, int performanceOrderIndex,
            int ticketIndex) {
        if (performance.id == 6001) {
            if (performanceOrderIndex == 0) {
                return allocateSpecificSeat(dataset, performance, purchaseId, customerId, ticketId,
                        "Orchestra", "A", 5 + ticketIndex);
            }
            int balconySeat = ((performanceOrderIndex - 1) * TICKETS_PER_PURCHASE) + ticketIndex + 1;
            return allocateSpecificSeat(dataset, performance, purchaseId, customerId, ticketId,
                    "Balcony", "C", balconySeat);
        }
        if (performance.id == 6002 && performanceOrderIndex == 0) {
            return allocateGeneralAdmission(dataset, performance, purchaseId, customerId, ticketId);
        }

        List<SeatInventory> seats = dataset.seatsByPerformance.getOrDefault(
                performance.id, Collections.emptyList());
        for (SeatInventory seat : seats) {
            if (!seat.blocked && !seat.allocated) {
                seat.allocated = true;
                String tierCode = performance.sectionTiers.get(seat.sectionName);
                return TicketSpec.reserved(ticketId, purchaseId, performance.id, customerId,
                        tierCode, seat.id, performance.tierPrices.get(tierCode));
            }
        }
        return allocateGeneralAdmission(dataset, performance, purchaseId, customerId, ticketId);
    }

    private static TicketSpec allocateSpecificSeat(Dataset dataset, PerformanceSpec performance,
            int purchaseId, int customerId, int ticketId, String sectionName,
            String rowName, int seatNumber) {
        for (SeatInventory seat : dataset.seatsByPerformance.get(performance.id)) {
            if (seat.sectionName.equals(sectionName) && seat.rowName.equals(rowName)
                    && seat.seatNumber == seatNumber) {
                require(!seat.blocked && !seat.allocated,
                        "Requested deterministic reserved seat is unavailable.");
                seat.allocated = true;
                String tierCode = performance.sectionTiers.get(sectionName);
                return TicketSpec.reserved(ticketId, purchaseId, performance.id, customerId,
                        tierCode, seat.id, performance.tierPrices.get(tierCode));
            }
        }
        throw new IllegalStateException("Deterministic reserved seat was not generated.");
    }

    private static TicketSpec allocateGeneralAdmission(Dataset dataset, PerformanceSpec performance,
            int purchaseId, int customerId, int ticketId) {
        for (GaInventory ga : dataset.gaByPerformance.getOrDefault(
                performance.id, Collections.emptyList())) {
            if (ga.allocatedCount < ga.totalCapacity) {
                ga.allocatedCount++;
                ga.activeSoldCount++;
                String tierCode = performance.sectionTiers.get(ga.sectionName);
                return TicketSpec.general(ticketId, purchaseId, performance.id, customerId,
                        tierCode, ga.id, performance.tierPrices.get(tierCode));
            }
        }
        throw new IllegalStateException("Performance " + performance.id
                + " does not have enough inventory for the deterministic ticket allocation.");
    }

    private static void createCancellations(Dataset dataset) {
        int nextCancellationId = 11001;
        int nextRefundId = 12001;

        for (TicketSpec ticket : dataset.tickets) {
            if (CANCELLED_PERFORMANCES.contains(ticket.performanceId)) {
                PerformanceSpec performance = performanceById(dataset, ticket.performanceId);
                EventSpec event = eventById(dataset, performance.eventId);
                String cancellationDate = daysAgoExpression(performance.cancellationDaysAgo);
                cancelTicket(dataset, ticket, nextCancellationId++, nextRefundId++,
                        event.organizerId, cancellationDate, "Organizer cancelled the performance");
            }
        }

        Set<Integer> cancellingCustomers = new HashSet<>();
        int customerCancellationIndex = 0;
        for (TicketSpec ticket : dataset.tickets) {
            if (customerCancellationIndex >= 12) {
                break;
            }
            PerformanceSpec performance = performanceById(dataset, ticket.performanceId);
            if (!"scheduled".equals(performance.status) || performance.offsetDays <= 7
                    || ticket.customerId < 2003 || ticket.id == DOUBLE_RESALE_TICKET
                    || ticket.performanceId == SPECIAL_AVAILABLE_PERFORMANCE
                    || cancellingCustomers.contains(ticket.customerId)) {
                continue;
            }
            String cancellationDate = daysAgoExpression(2 + customerCancellationIndex);
            cancelTicket(dataset, ticket, nextCancellationId++, nextRefundId++, ticket.customerId,
                    cancellationDate, "Customer cancelled before the seven-day deadline");
            cancellingCustomers.add(ticket.customerId);
            customerCancellationIndex++;
        }
        require(customerCancellationIndex == 12,
                "The dataset must contain twelve customer-cancelled tickets.");
    }

    private static void cancelTicket(Dataset dataset, TicketSpec ticket, int cancellationId,
            int refundId, int cancelledByUserId, String cancellationDate, String reason) {
        require("active".equals(ticket.status), "A deterministic ticket cannot be cancelled twice.");
        ticket.status = "cancelled";
        if (ticket.gaCapacityId != null) {
            GaInventory ga = gaById(dataset, ticket.gaCapacityId);
            ga.activeSoldCount--;
        }
        dataset.cancellations.add(new CancellationSpec(cancellationId, refundId, ticket.id,
                initialOwnershipId(ticket.id), cancelledByUserId, cancellationDate,
                reason, ticket.faceValueCents));
    }

    private static void createResaleMarket(Dataset dataset) {
        createScalperListings(dataset, 2001, 2050);
        createScalperListings(dataset, 2002, 2060);

        TicketSpec ticket = ticketById(dataset, DOUBLE_RESALE_TICKET);
        require("active".equals(ticket.status), "The twice-resold ticket must remain active.");
        ListingSpec firstSale = createListing(dataset, ticket, initialOwnershipId(ticket.id),
                ticket.customerId, "sold", true, 2099, 18, 14);
        createListing(dataset, ticket, firstSale.sale.newOwnershipId, 2099,
                "sold", false, 2100, 10, 6);
    }

    private static void createScalperListings(Dataset dataset, int customerId, int buyerBase) {
        List<TicketSpec> past = new ArrayList<>();
        List<TicketSpec> future = new ArrayList<>();
        for (TicketSpec ticket : dataset.tickets) {
            if (ticket.customerId != customerId || !"active".equals(ticket.status)) {
                continue;
            }
            PerformanceSpec performance = performanceById(dataset, ticket.performanceId);
            if (performance.offsetDays < 0) {
                past.add(ticket);
            } else if ("scheduled".equals(performance.status)) {
                future.add(ticket);
            }
        }
        require(past.size() >= 5 && future.size() >= 2,
                "Each deterministic scalper needs past and future tickets.");

        List<TicketSpec> selected = new ArrayList<>();
        selected.addAll(past.subList(0, 5));
        selected.addAll(future.subList(0, 2));
        for (int index = 0; index < selected.size(); index++) {
            String status = index < 3 ? "sold" : index < 5 ? "withdrawn" : "active";
            boolean exactlyAtCap = index == 0 || index == 5;
            int buyerId = buyerBase + index;
            PerformanceSpec performance = performanceById(dataset, selected.get(index).performanceId);
            int listedDaysAgo = performance.offsetDays < 0 ? 45 - index : 12 - index;
            int soldDaysAgo = listedDaysAgo - 5;
            createListing(dataset, selected.get(index),
                    initialOwnershipId(selected.get(index).id), customerId, status,
                    exactlyAtCap, buyerId, listedDaysAgo, soldDaysAgo);
        }
    }

    private static ListingSpec createListing(Dataset dataset, TicketSpec ticket,
            int sellerOwnershipId, int sellerCustomerId, String status, boolean exactlyAtCap,
            int buyerId, int listedDaysAgo, int soldDaysAgo) {
        EventSpec event = eventById(dataset,
                performanceById(dataset, ticket.performanceId).eventId);
        int capPrice = (ticket.faceValueCents * event.resaleCapHundredths) / 100;
        int listingPrice = exactlyAtCap ? capPrice
                : Math.min(capPrice, (ticket.faceValueCents * 110) / 100);
        ListingSpec listing = new ListingSpec(dataset.nextListingId++, ticket.id,
                sellerOwnershipId, listingPrice, capPrice, status,
                daysAgoExpression(listedDaysAgo));
        dataset.listings.add(listing);
        dataset.listedTicketIds.add(ticket.id);

        if ("sold".equals(status)) {
            require(buyerId != sellerCustomerId, "A resale buyer must differ from the seller.");
            int transactionId = dataset.nextResaleTransactionId++;
            int ownershipId = dataset.nextTransferOwnershipId++;
            String saleDate = daysAgoExpression(soldDaysAgo);
            TransactionSpec transaction = TransactionSpec.resale(transactionId, buyerId,
                    paymentId(buyerId), listing.id, saleDate);
            listing.sale = new SaleSpec(transaction, sellerOwnershipId, ownershipId,
                    buyerId, saleDate);
        }
        return listing;
    }

    private static void createReviews(Dataset dataset) {
        int reviewSequence = 0;
        for (int eventId = 5001; eventId <= 5010; eventId++) {
            Set<String> customerPerformancePairs = new HashSet<>();
            int reviewsForEvent = 0;
            for (TicketSpec ticket : dataset.tickets) {
                PerformanceSpec performance = performanceById(dataset, ticket.performanceId);
                if (performance.eventId != eventId || !"completed".equals(performance.status)
                        || !"active".equals(ticket.status)
                        || dataset.listedTicketIds.contains(ticket.id)) {
                    continue;
                }
                String pair = ticket.customerId + ":" + ticket.performanceId;
                if (!customerPerformancePairs.add(pair)) {
                    continue;
                }
                String comment = reviewComment(reviewSequence++);
                int eventRating = 3 + (reviewsForEvent % 3);
                int venueRating = 3 + ((reviewsForEvent + 1) % 3);
                int reviewDaysAgo = Math.max(1, (-performance.offsetDays) - 2);
                dataset.reviews.add(new ReviewSpec(ticket.customerId, performance.id,
                        comment, eventRating, venueRating, daysAgoExpression(reviewDaysAgo)));
                reviewsForEvent++;
                if (reviewsForEvent == 3) {
                    break;
                }
            }
            require(reviewsForEvent == 3,
                    "Each of the ten reviewed events must have three reviews.");
        }
    }

    private static String reviewComment(int sequence) {
        String[] openings = {
            "The live performance created a warm atmosphere and the sound design stayed clear throughout the evening.",
            "The stage production used thoughtful lighting and the lead performers held the audience's attention.",
            "The event pacing felt energetic and the crowd response made the headline moments memorable."
        };
        String[] middles = {
            "The venue staff gave helpful directions, and the seating area was comfortable and easy to reach.",
            "The main floor had a strong view of the stage, while the entry process moved at a steady pace.",
            "The musical arrangements, audience energy, and venue layout worked especially well together."
        };
        return openings[sequence % openings.length] + " "
                + middles[(sequence / openings.length) % middles.length] + " "
                + "The overall experience offered memorable music, friendly service, and a welcoming crowd.";
    }

    private static void validateDataset(Dataset dataset) {
        require(dataset.venues.size() == VENUE_COUNT, "Exactly eight venues are required.");
        Set<String> cities = new HashSet<>();
        Set<String> countries = new HashSet<>();
        int mixedVenues = 0;
        for (VenueSpec venue : dataset.venues) {
            cities.add(venue.city);
            countries.add(venue.country);
            require(venue.sections.size() >= 3, "Every venue must have several sections.");
            boolean reserved = venue.sections.stream().anyMatch(section -> !section.generalAdmission);
            boolean general = venue.sections.stream().anyMatch(section -> section.generalAdmission);
            if (reserved && general) {
                mixedVenues++;
            }
        }
        require(cities.size() >= 4 && countries.size() >= 2 && mixedVenues >= 2,
                "Venue geography and seating minimums are not satisfied.");
        require(dataset.venues.get(0).postalCode.startsWith("M5J")
                        && dataset.venues.get(1).postalCode.startsWith("M5J")
                        && dataset.venues.get(2).postalCode.startsWith("M5J"),
                "Three nearby Toronto venues must share the M5J postal area.");

        require(dataset.events.size() == EVENT_COUNT, "Exactly twenty events are required.");
        require(dataset.events.stream().map(event -> event.organizerId).distinct().count()
                        >= ORGANIZER_COUNT,
                "At least five organizers must manage events.");
        require(dataset.events.stream().anyMatch(event -> event.artistIds.size() > 1),
                "At least one event must have multiple billed artists.");
        require(dataset.performances.size() == PERFORMANCE_COUNT,
                "Exactly sixty performances are required.");
        require(dataset.performances.stream().anyMatch(performance -> performance.offsetDays < 0)
                        && dataset.performances.stream().anyMatch(performance -> performance.offsetDays > 0),
                "Both past and upcoming performances are required.");
        require(dataset.performances.stream().filter(performance -> performance.eventId == 5001)
                        .map(performance -> performance.venueId).distinct().count() >= 4,
                "The touring event must visit several venues.");
        require(dataset.performances.stream().filter(performance -> performance.eventId == 5002
                        && performance.venueId == 3002).count() == 12,
                "The theatre event must have many performances at one venue.");

        for (PerformanceSpec performance : dataset.performances) {
            require(performance.tierPrices.size() >= 2,
                    "Every performance must have at least two price tiers.");
            require(performance.sectionTiers.size()
                            == venueById(dataset, performance.venueId).sections.size(),
                    "Every performance section must have exactly one tier assignment.");
        }
        PerformanceSpec firstSetup = performanceById(dataset, 6001);
        PerformanceSpec secondSetup = performanceById(dataset, 6002);
        require(!firstSetup.tierPrices.equals(secondSetup.tierPrices)
                        && !firstSetup.sectionTiers.equals(secondSetup.sectionTiers),
                "The two Toronto performances must use different prices and tier mappings.");
        require(dataset.seatInventory.stream().anyMatch(seat -> seat.blocked),
                "Performance-specific blocked seats are required.");

        for (int performanceId : CONFIGURABLE_PERFORMANCES) {
            PerformanceSpec performance = performanceById(dataset, performanceId);
            require("scheduled".equals(performance.status) && performance.offsetDays > 0,
                    "Configurable performance " + performanceId
                            + " must be scheduled in the future.");
            require(dataset.tickets.stream().noneMatch(ticket ->
                            ticket.performanceId == performanceId),
                    "Configurable performance " + performanceId
                            + " must not have sold tickets.");
        }

        require(dataset.purchases.size() == PURCHASE_COUNT,
                "Exactly 320 purchase orders are required.");
        require(dataset.tickets.size() == TICKET_COUNT,
                "Exactly 960 tickets are required.");
        Map<Integer, Integer> ticketsByPurchase = new HashMap<>();
        for (TicketSpec ticket : dataset.tickets) {
            ticketsByPurchase.merge(ticket.purchaseId, 1, Integer::sum);
        }
        require(ticketsByPurchase.values().stream().allMatch(count -> count == TICKETS_PER_PURCHASE),
                "Every deterministic purchase must contain three tickets.");

        validateSalesExamples(dataset);
        validateAvailabilityExamples(dataset);

        require(dataset.cancellations.size() >= 40,
                "Customer and organizer cancellations with refunds are required.");
        require(dataset.cancellations.stream().map(cancellation -> cancellation.cancelledByUserId)
                        .filter(userId -> userId >= FIRST_CUSTOMER_ID).distinct().count() >= 5,
                "Several different customers must have cancellation records.");
        require(CANCELLED_PERFORMANCES.stream().allMatch(performanceId ->
                        "cancelled".equals(performanceById(dataset, performanceId).status)),
                "Two organizer-cancelled performances are required.");

        require(dataset.listings.stream().anyMatch(listing -> "active".equals(listing.status))
                        && dataset.listings.stream().anyMatch(listing -> "withdrawn".equals(listing.status))
                        && dataset.listings.stream().anyMatch(listing -> "sold".equals(listing.status)),
                "Active, withdrawn, and sold resale listings are required.");
        require(dataset.listings.stream().filter(listing -> listing.listingPriceCents
                        == listing.capPriceCents).count() >= 2,
                "Several listings must be priced exactly at the resale cap.");
        require(dataset.listings.stream().filter(listing -> listing.ticketId == DOUBLE_RESALE_TICKET
                        && "sold".equals(listing.status)).count() == 2,
                "One ticket must change owners twice.");
        validateScalper(dataset, 2001);
        validateScalper(dataset, 2002);

        Map<Integer, Long> reviewsByEvent = new HashMap<>();
        for (ReviewSpec review : dataset.reviews) {
            int eventId = performanceById(dataset, review.performanceId).eventId;
            reviewsByEvent.merge(eventId, 1L, Long::sum);
            require(review.comment.split("\\.").length >= 3,
                    "Review comments must contain several sentences.");
        }
        require(reviewsByEvent.size() >= 10
                        && reviewsByEvent.values().stream().allMatch(count -> count >= 3),
                "At least ten events must have several reviews each.");
    }

    private static void validateSalesExamples(Dataset dataset) {
        for (int performanceId : SOLD_OUT_PERFORMANCES) {
            PerformanceSpec performance = performanceById(dataset, performanceId);
            int activeTickets = (int) dataset.tickets.stream()
                    .filter(ticket -> ticket.performanceId == performanceId
                            && "active".equals(ticket.status)).count();
            require(activeTickets == sellableCapacity(dataset, performanceId),
                    "Sold-out performance " + performanceId + " must use all sellable capacity.");
        }
        for (int performanceId : LOW_SELL_THROUGH_PERFORMANCES) {
            int activeTickets = (int) dataset.tickets.stream()
                    .filter(ticket -> ticket.performanceId == performanceId
                            && "active".equals(ticket.status)).count();
            require(activeTickets * 4 < sellableCapacity(dataset, performanceId),
                    "Low-sell-through performance " + performanceId + " must remain below 25%.");
        }
        validatePerformanceSpread(dataset, SOLD_OUT_PERFORMANCES, "Sold-out");
        validatePerformanceSpread(dataset, LOW_SELL_THROUGH_PERFORMANCES,
                "Low-sell-through");

        Map<Integer, Set<String>> customerCities = new HashMap<>();
        Map<Integer, Integer> customerOrders = new HashMap<>();
        for (TransactionSpec purchase : dataset.purchases) {
            PerformanceSpec performance = performanceById(dataset, purchase.performanceId);
            String city = venueById(dataset, performance.venueId).city;
            customerCities.computeIfAbsent(purchase.customerId, ignored -> new HashSet<>()).add(city);
            customerOrders.merge(purchase.customerId, 1, Integer::sum);
        }
        long multiCityRepeatCustomers = customerOrders.entrySet().stream()
                .filter(entry -> entry.getValue() >= 2
                        && customerCities.get(entry.getKey()).size() >= 2).count();
        require(multiCityRepeatCustomers >= 5,
                "Several customers need repeat orders in multiple cities.");
    }

    private static void validatePerformanceSpread(Dataset dataset,
            Set<Integer> performanceIds, String label) {
        Set<String> cities = new HashSet<>();
        Set<Integer> monthBuckets = new HashSet<>();
        for (int performanceId : performanceIds) {
            PerformanceSpec performance = performanceById(dataset, performanceId);
            cities.add(venueById(dataset, performance.venueId).city);
            monthBuckets.add(Math.abs(performance.offsetDays) / 30);
        }
        require(cities.size() >= 3 && monthBuckets.size() >= 3,
                label + " examples must span at least three cities and months.");
    }

    private static void validateAvailabilityExamples(Dataset dataset) {
        Set<Integer> activeReservedSeatIds = new HashSet<>();
        for (TicketSpec ticket : dataset.tickets) {
            if ("active".equals(ticket.status) && ticket.performanceSeatId != null) {
                activeReservedSeatIds.add(ticket.performanceSeatId);
            }
        }

        for (int seatNumber = 1; seatNumber <= 4; seatNumber++) {
            SeatInventory seat = findSeat(dataset, SPECIAL_AVAILABLE_PERFORMANCE,
                    "Orchestra", "A", seatNumber);
            require(!seat.blocked && !activeReservedSeatIds.contains(seat.id),
                    "Orchestra row A seats 1-4 must remain consecutively available.");
        }

        List<Integer> rowBAvailable = new ArrayList<>();
        for (SeatInventory seat : dataset.seatsByPerformance.get(SPECIAL_AVAILABLE_PERFORMANCE)) {
            if ("Orchestra".equals(seat.sectionName) && "B".equals(seat.rowName)
                    && !seat.blocked && !activeReservedSeatIds.contains(seat.id)) {
                rowBAvailable.add(seat.seatNumber);
            }
        }
        Collections.sort(rowBAvailable);
        require(rowBAvailable.size() >= 2, "The nonconsecutive example row needs available seats.");
        for (int index = 1; index < rowBAvailable.size(); index++) {
            require(rowBAvailable.get(index) - rowBAvailable.get(index - 1) > 1,
                    "Only nonconsecutive seats may remain in Orchestra row B.");
        }

        require(dataset.gaByPerformance.get(SPECIAL_AVAILABLE_PERFORMANCE).stream()
                        .anyMatch(ga -> ga.activeSoldCount < ga.totalCapacity),
                "The future availability example needs remaining general admission capacity.");
        require(dataset.tickets.stream().anyMatch(ticket -> ticket.performanceId
                        == NEAR_DEADLINE_PERFORMANCE && "active".equals(ticket.status)),
                "The performance within seven days must have sold tickets.");

        PerformanceSpec special = performanceById(dataset, SPECIAL_AVAILABLE_PERFORMANCE);
        Set<String> soldTiers = new HashSet<>();
        for (TicketSpec ticket : dataset.tickets) {
            if (ticket.performanceId == special.id) {
                soldTiers.add(ticket.tierCode);
            }
        }
        require(soldTiers.contains("P1") && soldTiers.contains("P2") && !soldTiers.contains("P3"),
                "The future price-change example needs sold and unsold tiers.");
    }

    private static void validateScalper(Dataset dataset, int customerId) {
        long purchasedTickets = dataset.tickets.stream()
                .filter(ticket -> ticket.customerId == customerId).count();
        long listings = dataset.listings.stream()
                .filter(listing -> ticketById(dataset, listing.ticketId).customerId == customerId)
                .count();
        require(purchasedTickets >= 10 && listings * 2 > purchasedTickets,
                "Customer " + customerId + " must satisfy the possible-scalper threshold.");
    }

